function animateCounter(counter) {
const target = parseFloat(counter.dataset.target);
const suffix = counter.dataset.suffix || "";
const isFloat = counter.dataset.float === "true";

const duration = 1600;
const steps = 60;
let currentStep = 0;

const interval = setInterval(function () {
currentStep++;

const value = target * (currentStep / steps);

if (isFloat) {
    counter.textContent = value.toFixed(1) + suffix;
} else {
    counter.textContent = Math.round(value).toLocaleString() + suffix;
}

if (currentStep >= steps) {
    clearInterval(interval);

    if (isFloat) {
    counter.textContent = target.toFixed(1) + suffix;
    } else {
    counter.textContent = target.toLocaleString() + suffix;
    }
}
}, duration / steps);
}

function handleOrderSubmit(event) {
event.preventDefault();

const name = document.getElementById("oName").value.trim();
const email = document.getElementById("oEmail").value.trim();
const street = document.getElementById("oStreet").value.trim();
const city = document.getElementById("oCity").value.trim();
const zip = document.getElementById("oZip").value.trim();
const state = document.getElementById("oState").value.trim();
const qty = document.getElementById("oQty");

const formMessage = document.getElementById("formOk");
const btnText = document.getElementById("btnText");
const btnLoader = document.getElementById("btnLoader");
const stripeBtn = document.getElementById("stripeBtn");

if (!name || !email) {
const msg = currentLang === "es"
    ? "Por favor ingresa tu nombre y correo electrónico."
    : "Please enter your name and email.";

showFormMessage(msg, "error");
return;
}

if (!street || !city || !zip || !state) {
const msg = currentLang === "es"
    ? "Por favor completa tu dirección de envío."
    : "Please complete your shipping address.";

showFormMessage(msg, "error");
return;
}

const stripeLink = qty.value;

if (!stripeLink || stripeLink.startsWith("YOUR_STRIPE")) {
const msg = currentLang === "es"
    ? "⚠️ El pago todavía no está configurado."
    : "⚠️ Payment not configured yet.";

showFormMessage(msg, "error");
return;
}

if (btnText) {
btnText.style.display = "none";
}

if (btnLoader) {
btnLoader.style.display = "inline";
}

if (stripeBtn) {
stripeBtn.disabled = true;
}

if (formMessage) {
formMessage.style.color = "#4ade80";
formMessage.textContent = currentLang === "es"
    ? "Redirigiendo al pago seguro..."
    : "Redirecting to secure checkout...";
}

const url =
stripeLink +
"?prefilled_email=" +
encodeURIComponent(email) +
"&client_reference_id=" +
encodeURIComponent(name.replace(/\s+/g, "_"));

setTimeout(function () {
window.location.href = url;
}, 600);
}

function showFormMessage(message, type) {
const formMessage = document.getElementById("formOk");

if (!formMessage) return;

if (type === "error") {
formMessage.style.color = "#f87171";
} else {
formMessage.style.color = "#4ade80";
}

formMessage.textContent = message;
}
